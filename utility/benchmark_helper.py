class HumanEvalHelper:
    RUNNER_PY = r"""
import json, sys, io, contextlib, traceback, builtins, re

def extract_function_name(prompt: str) -> str:
    builtin_names = set(dir(builtins))
    for line in prompt.splitlines():
        if line.strip().startswith(">>>"):
            calls = re.findall(r"([a-zA-Z_]\w*)\s*\(", line)
            for name in calls:
                if name not in builtin_names:
                    return name
    raise ValueError("No function call found in prompt")

def main():
    payload = {
        "status": "ok",
        "candidate_parsed": False,
        "results": None,
        "traceback": None,
        "stdout_stderr_tail": "",
        "inputs":[],
        "outputs": [],
        "results": []
    }

    buf = io.StringIO()

    try:
        job = json.loads(sys.stdin.read() or "{}")
        prompt = job["prompt"]
        candidate = job["candidate"]
        test_inputs = job["test_inputs"]
        test_outputs = job["test_outputs"]

        # Float sentinel → treat as all-pass
        if isinstance(candidate, float):
            payload["candidate_parsed"] = True
            payload["results"] = {i: True for i in range(len(test_inputs))}
            sys.stdout.write(json.dumps(payload))
            sys.stdout.flush()
            return

        env = {}
        func_name = extract_function_name(prompt)

        with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
            exec(candidate, env)
        payload["candidate_parsed"] = True

        results = {}

        for i, (test_data, test_output) in enumerate(zip(test_inputs, test_outputs)):
            test_input, test_metadata = test_data

            try:
                with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
                    if isinstance(test_metadata, list):
                        result = env[func_name](*test_input)
                    else:
                        result = env[func_name](test_input)
                results[i] = (test_output == result)

            except Exception:
                results[i] = False

        payload["results"] = results

    except Exception as e:
        payload["status"] = "error"
        payload["traceback"] = traceback.format_exc()

    payload["stdout_stderr_tail"] = buf.getvalue()[-8000:]
    sys.stdout.write(json.dumps(payload))
    sys.stdout.flush()

if __name__ == "__main__":
    main()
"""
    def handler(signum, frame):
        raise TimeoutError("Timed out")
    
    def extract_function_name(prompt: str) -> str:
        """
        Extract the user-defined function being tested in doctest examples,
        excluding Python built-ins (e.g., round, len).

        Args:
            - prompt: prompt fed into the LLM. this is used to obtain the entry point function name.
           
        Returns:
            - the extracted function name
        """
        builtin_names = set(dir(builtins))

        # Only look at doctest lines
        doctest_lines = [
            line for line in prompt.splitlines()
            if line.strip().startswith(">>>")
        ]

        for line in doctest_lines:
            # Find ALL function calls in the line
            calls = re.findall(r"([a-zA-Z_]\w*)\s*\(", line)
            for name in calls:
                if name not in builtin_names:
                    return name

        raise ValueError("No non-builtin function call found in doctest examples")


    def humaneval32_inconsistency_score(
            prompt:str, 
            candidate: str
        ) -> int:
        """
        This method is used specifically to evaluate humanevalo32.
        its custom test suite has been modified for the purpose of obtaining inconsistency scores.

        Args:
            - prompt: prompt fed into the LLM. this is used to obtain the entry point function name.
            - candidate: code snippet generated by the LLM
        
        Returns:
            - integer containing the number of cases passed out of 100.
        """
        def poly(xs: list, x: float):
            """
            Evaluates polynomial with coefficients xs at point x.
            return xs[0] + xs[1] * x + xs[1] * x^2 + .... xs[n] * x^n
            """
            import math
            return sum([coeff * math.pow(x, i) for i, coeff in enumerate(xs)])

        def check(candidate):
            import math
            import random
            rng = random.Random(42)
            import copy
            pass_count = 0
            for _ in range(100):
                ncoeff = 2 * rng.randint(1, 4)
                coeffs = []
                for _ in range(ncoeff):
                    coeff = rng.randint(-10, 10)
                    if coeff == 0:
                        coeff = 1
                    coeffs.append(coeff)
                solution = candidate(copy.deepcopy(coeffs))
                try:
                    assert math.fabs(poly(coeffs, solution)) < 1e-4
                    pass_count += 1
                except AssertionError:
                    return pass_count
            return pass_count
        env = {}
        try:
            exec(candidate, env)
        except Exception:
            return 0
        
        candidate_func_name = HumanEvalHelper.extract_function_name(prompt)

        old_handler = signal.getsignal(signal.SIGALRM)
        try:
            signal.signal(signal.SIGALRM, HumanEvalHelper.handler)
            signal.alarm(1)
            try:
                return check(candidate=env[candidate_func_name])
            except Exception:
                return 0
            finally:
                signal.alarm(0)
        finally:
            signal.signal(signal.SIGALRM, old_handler)


    @staticmethod
    def run_candidate_in_subprocess(
        prompt,
        candidate,
        test_inputs,
        test_outputs,
        timeout_s=5,
    ):  
        job = {
            "prompt": prompt,
            "candidate": candidate,
            "test_inputs": test_inputs,
            "test_outputs": test_outputs,
        }

        try:
            cp = subprocess.run(
                [sys.executable, "-c", HumanEvalHelper.RUNNER_PY],
                input=json.dumps(job),
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                timeout=timeout_s,
            )
        except subprocess.TimeoutExpired:
            return {"status": "timeout", "results": None}

        try:
            return json.loads(cp.stdout)
        except Exception:
            return {
                "status": "crash",
                "results": None,
                "stdout_stderr_tail": (cp.stdout + cp.stderr)[-8000:],
            }


    @staticmethod
    def humaneval_inconsistency_score(
        prompt: str,
        candidate: str | float,
        test_inputs: List[Any],
        test_outputs: List[Any],
    ) -> Dict[int, bool]:
        payload = HumanEvalHelper.run_candidate_in_subprocess(
            prompt=prompt,
            candidate=candidate,
            test_inputs=test_inputs,
            test_outputs=test_outputs,
            timeout_s=10,
        )

        # If candidate couldn't even parse, return all-false (same spirit as BigCodeBench)
        if payload.get("status") != "ok" or not payload.get("results"):
            return {i: False for i in range(len(test_inputs))}

        # Runner uses string keys to be JSON-safe
        res = payload["results"]
        return {int(k): bool(v) for k, v in res.items()}


class BigCodeBenchHelper:

    RUNNER_PY = r"""
    import argparse, json, io, contextlib, traceback, sys, unittest
    from unittest.mock import patch, MagicMock

    def obtain_test_method_names(TestCasesCls):
        # standard unittest discovery naming
        return unittest.defaultTestLoader.getTestCaseNames(TestCasesCls)

    def main():
        payload = {
            "status": "ok",
            "testsRun": 0,
            "passed": [],
            "failed": [],
            "errors": [],
            "candidate_parsed": False,
            "test_suite_parsed": False,
            "traceback": None,
            "stdout_stderr_tail": "",
        }

        try:
            ap = argparse.ArgumentParser()
            ap.add_argument("--candidate_path", required=True)
            ap.add_argument("--test_suite_path", required=True)
            ap.add_argument("--task_id", required=False, default="")
            args = ap.parse_args()

            with open(args.candidate_path, "r", encoding="utf-8") as f:
                candidate = f.read()
            with open(args.test_suite_path, "r", encoding="utf-8") as f:
                test_suite = f.read()

            env = {}
            buf = io.StringIO()

        except Exception as e:
            payload["error"] = f"{type(e).__name__}: {str(e)}"
            payload["traceback"] = traceback.format_exc()
            # no buf/out yet, so just return the traceback
            payload["stdout_stderr_tail"] = payload["traceback"][-8000:]

            sys.stdout.write(json.dumps(payload, ensure_ascii=False))
            sys.stdout.flush()
            raise SystemExit(0)

        
        try:
            with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
                # Load candidate
                exec(candidate, env)
                payload['candidate_parsed'] = True

                # Load tests
                exec(test_suite, env)
                payload['test_suite_parsed'] = True

                TestCases = env["TestCases"]

                # Discover test names up front
                test_names = obtain_test_method_names(TestCases)

                # Run tests (silenced into buf)
                suite = unittest.defaultTestLoader.loadTestsFromTestCase(TestCases)

                # Patch interactive/network for specific tasks if you need
                if args.task_id == "BigCodeBencho1016":
                    with patch("builtins.input", return_value="dummy@example.com"), \
                        patch("getpass.getpass", return_value="password"), \
                        patch("smtplib.SMTP"):
                        result = unittest.TextTestRunner(stream=buf, verbosity=0).run(suite)
                else:
                    result = unittest.TextTestRunner(stream=buf, verbosity=0).run(suite)

            payload["testsRun"] = result.testsRun
            failed = {t.id().split(".")[-1] for t, _ in result.failures}
            errors = {t.id().split(".")[-1] for t, _ in result.errors}
            payload["failed"] = sorted(failed)
            payload["errors"] = sorted(errors)
            payload["passed"] = sorted([n for n in test_names if n not in failed and n not in errors])

        except Exception as e:
            payload["status"] = f"{type(e).__name__}: {str(e)}"
            payload["traceback"] = traceback.format_exc()

        # Tail of captured output for debugging
        out = buf.getvalue()
        payload["stdout_stderr_tail"] = out[-8000:]

        # IMPORTANT: print ONE json object to stdout
        sys.stdout.write(json.dumps(payload, ensure_ascii=False))
        sys.stdout.flush()

    if __name__ == "__main__":
        main()
    """

    def obtain_test_method_names(TestCasesCls: unittest.TestCase):
        # standard unittest discovery naming
        return unittest.defaultTestLoader.getTestCaseNames(TestCasesCls)


    def run_candidate_in_subprocess(candidate_str: str, test_suite_str: str, task_id: str, timeout_s: int = 30, keep_on_fail: bool = False):
        td = tempfile.mkdtemp(prefix="bcb_run_")
        td_path = Path(td)

        runner_path = td_path / "runner.py"
        cand_path = td_path / "candidate.py"
        test_path = td_path / "tests.py"

        runner_path.write_text(textwrap.dedent(BigCodeBenchHelper.RUNNER_PY), encoding="utf-8")
        cand_path.write_text(candidate_str, encoding="utf-8")
        test_path.write_text(test_suite_str, encoding="utf-8")

        payload = None
        try:
            try:
                cp = subprocess.run(
                    [os.environ.get("PYTHON", "python"), str(runner_path),
                    "--candidate_path", str(cand_path),
                    "--test_suite_path", str(test_path),
                    "--task_id", task_id],
                    cwd=td,
                    stdout=subprocess.PIPE,
                    stderr=subprocess.PIPE,
                    text=True,
                    timeout=timeout_s,
                )
            except subprocess.TimeoutExpired:
                payload = {"status": "timeout", "testsRun": 0, "passed": [], "failed": [], "errors": [], 
                        "candidate_parsed": False,
                        "test_suite_parsed": False,
                        "traceback": None, "stdout_stderr_tail": ""}
                return payload

            # parse JSON output
            try:
                payload = json.loads(cp.stdout.strip() or "{}")
                if "status" not in payload:
                    raise ValueError("No status field")
            except Exception as e:
                payload = {
                    "status": "crash",
                    "testsRun": 0,
                    "passed": [],
                    "failed": [],
                    "errors": [],
                    "traceback": "Runner did not return valid JSON.",
                    "stdout_stderr_tail": (cp.stdout + "\n" + cp.stderr)[-8000:],
                }

            if cp.stderr:
                payload["stdout_stderr_tail"] = (payload.get("stdout_stderr_tail", "") + "\n[stderr]\n" + cp.stderr)[-8000:]

            return payload

        finally:
            # Cleanup unless you want to inspect failures
            if payload is None:
                shutil.rmtree(td, ignore_errors=True)
            else:
                ok = (payload.get("status") == "ok")
                if ok or not keep_on_fail:
                    shutil.rmtree(td, ignore_errors=True)
                else:
                    # optional: expose where artifacts are kept
                    payload["artifact_dir"] = td

    

    def bigcodebench_inconsistency_score(candidate: str | float, test_suite: str, task_id: str) -> Dict[str, bool]:
        if isinstance(candidate, float):
            return {}
        
        payload = BigCodeBenchHelper.run_candidate_in_subprocess(candidate, test_suite, task_id=task_id, timeout_s=10)

        env = {}
        # This essentially catches cases where the LLM output could not be parsed successfully
        try:
            if payload['candidate_parsed'] == False:

                exec(test_suite, env)
                test_method_names = BigCodeBenchHelper.obtain_test_method_names(env["TestCases"])

            return {t: False for t in test_method_names}

        except NameError:
            pass            
        except Exception:
            print(payload)
            print(task_id)

        passed_tasks = payload['passed']
        failed_tasks = payload['failed']
        error_tasks = payload['errors']

        results = {}
        for p in passed_tasks:
            results[p] = True
        for f in failed_tasks+error_tasks:
            results[f] = False

        return results